classdef dt_db
    %DT_DB Capa de persistencia SQLite para el gemelo digital SPACEWISE AI.
    %   Proporciona creación del esquema y métodos de inserción/consulta
    %   sobre la base bd/spacewise.db usando la función sqlite de Database
    %   Toolbox (R2022a+).

    methods (Static)

        function conn = open(dbPath, createFlag)
            %OPEN Abre (y opcionalmente crea) la base SQLite.
            %   conn = dt_db.open(dbPath)         abre la base existente.
            %   conn = dt_db.open(dbPath, true)   crea la base si no existe.
            if nargin < 2
                createFlag = false;
            end
            if createFlag && ~exist(dbPath, 'file')
                conn = sqlite(dbPath, 'create');
            else
                conn = sqlite(dbPath);
            end
        end

        function conn = init(dbPath)
            %INIT Crea la base y el esquema completo (idempotente).
            if exist(dbPath, 'file')
                delete(dbPath);
            end
            conn = sqlite(dbPath, 'create');
            dt_db.createSchema(conn);
        end

        function close(conn)
            %CLOSE Cierra la conexión si está abierta.
            if conn.isopen
                conn.close();
            end
        end

        function createSchema(conn)
            %CREATESCHEMA Ejecuta el DDL del esquema (CREATE TABLE IF NOT EXISTS).
            ddl = dt_db.schemaDDL();
            for k = 1:numel(ddl)
                conn.execute(ddl{k});
            end
        end

        function id = lastInsertId(conn)
            %LASTINSERTID Devuelve el último rowid insertado.
            r = conn.fetch('SELECT last_insert_rowid() AS id');
            id = r.id;
        end

        function insertDeviceTypes(conn, T)
            %INSERTDEVICETYPES Inserta el catálogo de tipos de dispositivo.
            sqlwrite(conn, 'device_types', T);
        end

        function insertDevices(conn, T)
            %INSERTDEVICES Inserta el catálogo de dispositivos.
            sqlwrite(conn, 'devices', T);
        end

        function scenario_id = insertScenario(conn, code, name, desc, params_json, is_baseline)
            %INSERTSCENARIO Inserta un escenario y devuelve su scenario_id.
            if nargin < 6
                is_baseline = 0;
            end
            params_json = char(jsonencode(params_json));
            sql = sprintf("INSERT INTO scenarios (scenario_code,name,description,params_json,is_baseline,created_at) VALUES ('%s','%s','%s','%s',%d,datetime('now'))", ...
                escapeSQL(code), escapeSQL(name), escapeSQL(desc), escapeSQL(params_json), is_baseline);
            conn.execute(sql);
            scenario_id = dt_db.lastInsertId(conn);
        end

        function sim_id = insertSimulation(conn, scenario_id, engine_version)
            %INSERTSIMULATION Crea un registro de simulación en curso.
            sql = sprintf("INSERT INTO simulations (scenario_id,engine_version,start_time,status) VALUES (%d,'%s',datetime('now'),'RUNNING')", ...
                scenario_id, escapeSQL(engine_version));
            conn.execute(sql);
            sim_id = dt_db.lastInsertId(conn);
        end

        function finishSimulation(conn, sim_id, status, logtext)
            %FINISHSIMULATION Cierra el registro de simulación.
            if nargin < 4
                logtext = '';
            end
            logtext = char(string(logtext));
            sql = sprintf("UPDATE simulations SET status='%s', end_time=datetime('now'), log='%s' WHERE simulation_id=%d", ...
                escapeSQL(status), escapeSQL(logtext), sim_id);
            conn.execute(sql);
        end

        function insertEnvironment(conn, sim_id, T)
            %INSERTENVIRONMENT Guarda la serie horaria ambiental.
            if height(T) == 0, return; end
            T.simulation_id = repmat(sim_id, height(T), 1);
            T = movevars(T, 'simulation_id', 'Before', 'ts');
            sqlwrite(conn, 'environment', T);
        end

        function insertMeasurements(conn, sim_id, T)
            %INSERTMEASUREMENTS Guarda las mediciones horarias por dispositivo.
            if height(T) == 0, return; end
            T.simulation_id = repmat(sim_id, height(T), 1);
            T = movevars(T, 'simulation_id', 'Before', 'ts');
            sqlwrite(conn, 'measurements', T);
        end

        function insertProfiles(conn, sim_id, T)
            %INSERTPROFILES Guarda los perfiles horarios por subsistema.
            if height(T) == 0, return; end
            T.simulation_id = repmat(sim_id, height(T), 1);
            T = movevars(T, 'simulation_id', 'Before', 'subsystem');
            sqlwrite(conn, 'subsystem_profiles', T);
        end

        function insertResults(conn, sim_id, T)
            %INSERTRESULTS Guarda los KPIs por subsistema y TOTAL.
            if height(T) == 0, return; end
            T.simulation_id = repmat(sim_id, height(T), 1);
            T = movevars(T, 'simulation_id', 'Before', 'subsystem');
            sqlwrite(conn, 'simulation_results', T);
        end

        function insertEvents(conn, sim_id, T)
            %INSERTEVENTS Guarda alarmas/anomalías.
            if height(T) == 0, return; end
            T.simulation_id = repmat(sim_id, height(T), 1);
            T = movevars(T, 'simulation_id', 'Before', 'ts');
            sqlwrite(conn, 'events', T);
        end

        function T = query(conn, sql)
            %QUERY Ejecuta una consulta SELECT y devuelve una tabla.
            T = conn.fetch(sql);
        end

    end

    methods (Static, Access = private)

        function ddl = schemaDDL()
            %SCHEMADDL Devuelve las sentencias CREATE TABLE del esquema.
            ddl = { ...
                "CREATE TABLE IF NOT EXISTS device_types (" + ...
                "  type_id INTEGER PRIMARY KEY," + ...
                "  type_code TEXT UNIQUE NOT NULL," + ...
                "  type_name TEXT NOT NULL," + ...
                "  description TEXT" + ...
                ")";
                "CREATE TABLE IF NOT EXISTS devices (" + ...
                "  device_id INTEGER PRIMARY KEY," + ...
                "  device_code TEXT UNIQUE NOT NULL," + ...
                "  name TEXT NOT NULL," + ...
                "  type_code TEXT NOT NULL REFERENCES device_types(type_code)," + ...
                "  subsystem TEXT NOT NULL," + ...
                "  criticality TEXT NOT NULL," + ...
                "  manufacturer TEXT," + ...
                "  model TEXT," + ...
                "  rated_power_kw REAL NOT NULL," + ...
                "  pf_nominal REAL," + ...
                "  thd_nominal_pct REAL," + ...
                "  voltage_v REAL," + ...
                "  phases INTEGER," + ...
                "  location TEXT," + ...
                "  install_date TEXT," + ...
                "  active INTEGER DEFAULT 1," + ...
                "  metadata_json TEXT" + ...
                ")";
                "CREATE TABLE IF NOT EXISTS scenarios (" + ...
                "  scenario_id INTEGER PRIMARY KEY," + ...
                "  scenario_code TEXT UNIQUE NOT NULL," + ...
                "  name TEXT NOT NULL," + ...
                "  description TEXT," + ...
                "  params_json TEXT NOT NULL," + ...
                "  is_baseline INTEGER DEFAULT 0," + ...
                "  created_at TEXT" + ...
                ")";
                "CREATE TABLE IF NOT EXISTS simulations (" + ...
                "  simulation_id INTEGER PRIMARY KEY," + ...
                "  scenario_id INTEGER NOT NULL REFERENCES scenarios(scenario_id)," + ...
                "  engine_version TEXT," + ...
                "  start_time TEXT," + ...
                "  end_time TEXT," + ...
                "  status TEXT," + ...
                "  log TEXT" + ...
                ")";
                "CREATE TABLE IF NOT EXISTS environment (" + ...
                "  env_id INTEGER PRIMARY KEY," + ...
                "  simulation_id INTEGER NOT NULL REFERENCES simulations(simulation_id)," + ...
                "  ts TEXT NOT NULL," + ...
                "  temp_c REAL," + ...
                "  humidity_pct REAL," + ...
                "  co2_ppm REAL," + ...
                "  occupancy REAL," + ...
                "  solar_wm2 REAL," + ...
                "  weekday INTEGER," + ...
                "  hour INTEGER" + ...
                ")";
                "CREATE INDEX IF NOT EXISTS idx_env_sim ON environment(simulation_id)";
                "CREATE TABLE IF NOT EXISTS measurements (" + ...
                "  measurement_id INTEGER PRIMARY KEY," + ...
                "  simulation_id INTEGER NOT NULL REFERENCES simulations(simulation_id)," + ...
                "  device_id INTEGER NOT NULL REFERENCES devices(device_id)," + ...
                "  ts TEXT NOT NULL," + ...
                "  voltage_v REAL," + ...
                "  current_a REAL," + ...
                "  active_power_kw REAL," + ...
                "  reactive_power_kvar REAL," + ...
                "  power_factor REAL," + ...
                "  energy_kwh REAL," + ...
                "  thd_pct REAL," + ...
                "  status TEXT" + ...
                ")";
                "CREATE INDEX IF NOT EXISTS idx_meas_sim_dev ON measurements(simulation_id, device_id)";
                "CREATE INDEX IF NOT EXISTS idx_meas_dev_ts ON measurements(device_id, ts)";
                "CREATE TABLE IF NOT EXISTS subsystem_profiles (" + ...
                "  profile_id INTEGER PRIMARY KEY," + ...
                "  simulation_id INTEGER NOT NULL REFERENCES simulations(simulation_id)," + ...
                "  subsystem TEXT NOT NULL," + ...
                "  ts TEXT NOT NULL," + ...
                "  power_base_kw REAL," + ...
                "  power_ctrl_kw REAL" + ...
                ")";
                "CREATE INDEX IF NOT EXISTS idx_prof_sim ON subsystem_profiles(simulation_id)";
                "CREATE TABLE IF NOT EXISTS simulation_results (" + ...
                "  result_id INTEGER PRIMARY KEY," + ...
                "  simulation_id INTEGER NOT NULL REFERENCES simulations(simulation_id)," + ...
                "  subsystem TEXT NOT NULL," + ...
                "  energy_base_kwh REAL," + ...
                "  energy_ctrl_kwh REAL," + ...
                "  savings_kwh REAL," + ...
                "  savings_pct REAL," + ...
                "  peak_base_kw REAL," + ...
                "  peak_ctrl_kw REAL," + ...
                "  co2_base_ton REAL," + ...
                "  co2_ctrl_ton REAL," + ...
                "  co2_avoided_ton REAL," + ...
                "  rmse_kw REAL," + ...
                "  mae_kw REAL," + ...
                "  r2 REAL," + ...
                "  payback_years REAL," + ...
                "  van_usd REAL," + ...
                "  tir_pct REAL," + ...
                "  data_json TEXT" + ...
                ")";
                "CREATE INDEX IF NOT EXISTS idx_res_sim ON simulation_results(simulation_id)";
                "CREATE TABLE IF NOT EXISTS events (" + ...
                "  event_id INTEGER PRIMARY KEY," + ...
                "  simulation_id INTEGER NOT NULL REFERENCES simulations(simulation_id)," + ...
                "  device_id INTEGER REFERENCES devices(device_id)," + ...
                "  ts TEXT," + ...
                "  event_type TEXT," + ...
                "  severity TEXT," + ...
                "  message TEXT," + ...
                "  value REAL" + ...
                ")";
                };
        end

    end

end

function s = escapeSQL(s)
%ESCAPESQL Escapa comillas simples para inserción segura en SQLite.
s = strrep(string(s), "'", "''");
end
